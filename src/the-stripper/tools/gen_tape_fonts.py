#!/usr/bin/env python3
"""Convert the three tape fonts into vector glyph paths for the editor (spec 4, font del nastro).

The plug-in never loads a font: the glyph outlines of the printable ASCII set plus the ellipsis are generated into a C++
header (src/ui/tape_glyphs.h) and drawn as paths, so there is nothing to install or register on any platform.

Fonts (all open, downloaded from https://github.com/google/fonts):
  Zeyada          SIL Open Font License 1.1   ofl/zeyada/Zeyada.ttf
  Rock Salt       Apache License 2.0          apache/rocksalt/RockSalt-Regular.ttf
  Homemade Apple  Apache License 2.0          apache/homemadeapple/HomemadeApple-Regular.ttf

Dependencies: fontTools (pip install fonttools). Usage:
  gen_tape_fonts.py --zeyada Zeyada.ttf --rocksalt RockSalt-Regular.ttf --homemade HomemadeApple-Regular.ttf --out src/ui/tape_glyphs.h

Stream format of a glyph (int16 values, font units scaled to 1000 per em, y up): a sequence of
  0 x y            move to
  1 x y            line to
  2 cx cy x y      quadratic curve to
  3                close the contour
"""
import argparse
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

EM = 1000
CODEPOINTS = list(range(32, 127)) + [0x2026]   # printable ASCII and the ellipsis (used by the truncated names)

FONTS = [
    # key, display name, argument, license
    ("Zeyada", "Zeyada", "zeyada", "SIL Open Font License 1.1"),
    ("RockSalt", "Rock Salt", "rocksalt", "Apache License 2.0"),
    ("HomemadeApple", "Homemade Apple", "homemade", "Apache License 2.0"),
]

OP_MOVE, OP_LINE, OP_QUAD, OP_CLOSE = 0, 1, 2, 3


class StreamPen(BasePen):
    """Collects a glyph as the int16 op stream, scaled to EM units per em."""

    def __init__(self, glyph_set, scale):
        super().__init__(glyph_set)
        self.scale = scale
        self.stream = []

    def _pt(self, p):
        return [int(round(p[0] * self.scale)), int(round(p[1] * self.scale))]

    def _moveTo(self, pt):
        self.stream += [OP_MOVE] + self._pt(pt)

    def _lineTo(self, pt):
        self.stream += [OP_LINE] + self._pt(pt)

    def _qCurveToOne(self, pt1, pt2):
        self.stream += [OP_QUAD] + self._pt(pt1) + self._pt(pt2)

    def _curveToOne(self, pt1, pt2, pt3):   # cubic outlines (not in these fonts): approximate with a quadratic
        mid = ((pt1[0] + pt2[0]) / 2, (pt1[1] + pt2[1]) / 2)
        self.stream += [OP_QUAD] + self._pt(mid) + self._pt(pt3)

    def _closePath(self):
        self.stream += [OP_CLOSE]

    def _endPath(self):
        self.stream += [OP_CLOSE]


def convert_font(font):
    """-> dict with glyphs [(codepoint, advance, stream)], digit height and cap height (EM units)."""
    scale = EM / font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()
    glyphs = []
    for cp in CODEPOINTS:
        name = cmap.get(cp)
        if name is None:
            continue
        pen = StreamPen(glyph_set, scale)
        glyph_set[name].draw(pen)
        advance = int(round(font["hmtx"][name][0] * scale))
        glyphs.append((cp, advance, pen.stream))
    return {"glyphs": glyphs, "digit_height": digit_height(font, scale), "cap_height": measure(font, "H", scale)}


def measure(font, ch, scale):
    from fontTools.pens.boundsPen import BoundsPen
    glyph_set = font.getGlyphSet()
    name = font.getBestCmap()[ord(ch)]
    pen = BoundsPen(glyph_set)
    glyph_set[name].draw(pen)
    return 0 if pen.bounds is None else pen.bounds[3] * scale


def digit_height(font, scale):
    """Height of the digits above the baseline: the mean of the tops of 0-9 (what the editor normalises on)."""
    tops = [measure(font, d, scale) for d in "0123456789"]
    return sum(tops) / len(tops)


def render_header(converted):
    out = []
    w = out.append
    w("// GENERATED by tools/gen_tape_fonts.py: do not edit by hand.")
    w("// Glyph outlines of the three tape fonts (printable ASCII and the ellipsis), 1000 units per em, y up.")
    w("// Zeyada: SIL Open Font License 1.1. Rock Salt and Homemade Apple: Apache License 2.0 (texts in assets/fonts/).")
    w("// Stream: 0 x y = move, 1 x y = line, 2 cx cy x y = quadratic curve, 3 = close.")
    w("#pragma once")
    w("")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("")
    w("namespace FairyTapes::TheStripper::Ui::tape_glyphs {")
    w("")
    w("struct Glyph {")
    w("  std::uint32_t codepoint;")
    w("  std::int16_t advance;")
    w("  std::uint32_t offset;   // into the font's stream")
    w("  std::uint32_t count;    // number of int16 values")
    w("};")
    w("")
    w("struct Font {")
    w("  const char* name;")
    w("  const char* license;")
    w("  int unitsPerEm;")
    w("  double digitHeight;   // mean height of the digits 0-9 above the baseline, in units")
    w("  double capHeight;")
    w("  const Glyph* glyphs;")
    w("  std::size_t glyphCount;")
    w("  const std::int16_t* stream;")
    w("};")
    w("")
    fonts = []
    for key, display, _arg, license_ in FONTS:
        data = converted[key]
        stream, table = [], []
        for cp, advance, s in data["glyphs"]:
            table.append((cp, advance, len(stream), len(s)))
            stream += s
        w(f"inline constexpr Glyph k{key}Glyphs[] = {{")
        for cp, advance, off, n in table:
            w(f"    {{{cp}, {advance}, {off}, {n}}},")
        w("};")
        w(f"inline constexpr std::int16_t k{key}Stream[] = {{")
        for i in range(0, len(stream), 24):
            w("    " + ", ".join(str(v) for v in stream[i:i + 24]) + ",")
        w("};")
        w("")
        fonts.append((key, display, license_, data))
    w("inline constexpr Font kFonts[] = {")
    for key, display, license_, data in fonts:
        w(f'    {{"{display}", "{license_}", {EM}, {data["digit_height"]:.3f}, {data["cap_height"]:.3f}, k{key}Glyphs, '
          f"sizeof(k{key}Glyphs) / sizeof(k{key}Glyphs[0]), k{key}Stream}},")
    w("};")
    w("")
    w("}  // namespace FairyTapes::TheStripper::Ui::tape_glyphs")
    w("")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    for _key, _display, arg, _license in FONTS:
        ap.add_argument(f"--{arg}", required=True, help=f"path of the {arg} .ttf")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    converted = {}
    for key, _display, arg, _license in FONTS:
        converted[key] = convert_font(TTFont(getattr(args, arg)))
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render_header(converted))
    return 0


if __name__ == "__main__":
    sys.exit(main())
